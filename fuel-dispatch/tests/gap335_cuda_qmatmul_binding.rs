//! GAP-335, binding half closed by ROADMAP row 105 (0.30.10): a CUDA `QMatMul` dispatcher binding exists.
//! This file guards only that the binding is registered. It does NOT show the production realize selects
//! it: measured 2026-10-30 it does not (ROADMAP row 114).
//!
//! This file began as the detector for the opposite state (no binding; a lazy `qmatmul` on a CUDA
//! device never reached a CUDA quantized kernel) and was written to fail the day a binding was
//! added. That day is row 105, and the detector is flipped on purpose into the guard that the
//! binding stays: if the contract or its registration is removed, the quantized matmul silently
//! goes back to the CPU with a device round trip per use.
//!
//! Both arms are host-only, so every CI leg runs them. A binding-table read would need
//! `--features cuda`, which no CI leg builds (the live test is `baracuda_qmatmul_live`).
//!
//! 1. CONTRACTS. Every `fuel-dispatch/kernel-contracts/**/*.fkc.md` in the git index is parsed;
//!    exactly one kernel whose effective backend is `Cuda` names `QMatMul`, and it is
//!    `qmatmul_f32` in `cuda/qmatmul.fkc.md`. Control: Metal's contract does name `QMatMul`.
//! 2. SOURCE. `fuel-dispatch/src/baracuda_dispatch.rs` (the CUDA-gated file that loads the CUDA
//!    contracts) includes `cuda/qmatmul.fkc.md` and calls `register_cuda_qmatmul_from_contract`
//!    from `register_baracuda_cuda_kernels`; and no OTHER CUDA-gated source registers `QMatMul`
//!    by hand (the contract is the sole path). Controls: the predicate is checked on constructed
//!    input, and the scan reaches `baracuda_dispatch.rs` and recognises its gate.
//!
//! Blind spots: arm 2 cannot see a registration generated by a macro or spelled through an
//! aliased path, and arm 1 cannot see a CUDA contract kept outside `fuel-dispatch/kernel-contracts`.

use std::path::{Path, PathBuf};
use std::process::Command;

use fuel_dispatch::fkc::parse_file;

const WHY: &str = "ROADMAP row 105 / GAP-335: the CUDA QMatMul binding must exist, or quantized      weights run on the CPU with a device round trip per use again";

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("fuel-dispatch sits one level below the repo root")
        .to_path_buf()
}

/// Files under `dir` in the git index, filtered by `suffix`. Enumerating the
/// index (not the disk) keeps other worktrees and build output out of scope.
fn indexed(dir: &str, suffix: &str) -> Vec<PathBuf> {
    let root = repo_root();
    let out = Command::new("git")
        .args(["ls-files", "--", dir])
        .current_dir(&root)
        .output()
        .expect("git must be available to enumerate the index");
    assert!(
        out.status.success(),
        "git ls-files failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8(out.stdout)
        .expect("git ls-files output is utf-8")
        .lines()
        .filter(|p| p.ends_with(suffix))
        .map(|p| root.join(p))
        .collect()
}

fn names_qmatmul(kind: Option<&str>) -> bool {
    matches!(kind, Some("QMatMul") | Some("QMATMUL"))
}

#[test]
fn exactly_one_cuda_contract_kernel_binds_qmatmul() {
    let files = indexed("fuel-dispatch/kernel-contracts", ".fkc.md");
    assert!(
        files.len() > 50,
        "only {} contract files found",
        files.len()
    );

    let mut cuda_kernels = 0;
    let mut metal_qmatmul = 0;
    let mut bound = Vec::new();
    for path in &files {
        let text = std::fs::read_to_string(path).expect("read contract");
        let file = parse_file(&text).unwrap_or_else(|e| {
            panic!(
                "{} does not parse, so it cannot be checked: {e}",
                path.display()
            )
        });
        for k in &file.kernels {
            let backend = k
                .backend
                .as_deref()
                .unwrap_or(&file.front_matter.provider.backend);
            let qmatmul =
                names_qmatmul(k.op_kind.as_deref()) || names_qmatmul(k.fused_op.as_deref());
            match backend {
                "Cuda" => {
                    cuda_kernels += 1;
                    if qmatmul {
                        bound.push(format!("{} :: {}", path.display(), k.kernel));
                    }
                }
                "Metal" if qmatmul => metal_qmatmul += 1,
                _ => {}
            }
        }
    }
    // Controls: the arm can see CUDA kernels at all, and can see a QMatMul kernel.
    assert!(cuda_kernels > 0, "no CUDA kernel contracts were parsed");
    assert!(metal_qmatmul > 0, "the Metal QMatMul contract was not seen");
    assert_eq!(bound.len(), 1, "{WHY}: found {bound:?}");
    assert!(
        bound[0]
            .replace('\\', "/")
            .ends_with("kernel-contracts/cuda/qmatmul.fkc.md :: qmatmul_f32"),
        "{WHY}: the one CUDA QMatMul kernel is {:?}",
        bound[0]
    );
}

/// The text of `line` before any `//` comment.
fn code_part(line: &str) -> &str {
    line.split("//").next().unwrap_or("")
}

/// How many lines either side of a `QMatMul` mention to look for `BackendId::Cuda`.
const NEAR: usize = 12;

/// 1-based lines of `text` that mention `QMatMul` in code and are CUDA-gated:
/// the whole file is `#![cfg(feature = "cuda")]`, or `BackendId::Cuda` appears
/// in code within `NEAR` lines.
fn cuda_qmatmul_lines(text: &str) -> Vec<usize> {
    let code: Vec<&str> = text.lines().map(code_part).collect();
    let file_gated = text
        .lines()
        .any(|l| l.trim() == "#![cfg(feature = \"cuda\")]");
    (0..code.len())
        .filter(|&i| code[i].contains("OpKind::QMatMul") || code[i].contains("FusedOps::QMATMUL"))
        .filter(|&i| {
            let near = &code[i.saturating_sub(NEAR)..(i + NEAR + 1).min(code.len())];
            file_gated || near.iter().any(|l| l.contains("BackendId::Cuda"))
        })
        .map(|i| i + 1)
        .collect()
}

/// The predicate on constructed input: a CUDA registration is flagged, a
/// Vulkan one is not, and a comment does not count.
#[test]
fn the_source_predicate_flags_only_cuda_qmatmul() {
    let cuda =
        "fn reg(t: &mut T) {\n    t.register(OpKind::QMatMul, &[F32], BackendId::Cuda, k);\n}\n";
    assert_eq!(cuda_qmatmul_lines(cuda), vec![2]);
    let gated = "#![cfg(feature = \"cuda\")]\nfn f() { let _ = OpKind::QMatMul; }\n";
    assert_eq!(cuda_qmatmul_lines(gated), vec![2]);
    let vulkan = "t.register(OpKind::QMatMul, &[F32], BackendId::Vulkan, k);\n";
    assert!(cuda_qmatmul_lines(vulkan).is_empty());
    let comment = "// OpKind::QMatMul on BackendId::Cuda\n";
    assert!(cuda_qmatmul_lines(comment).is_empty());
}

#[test]
fn the_cuda_registration_file_loads_the_contract_and_nothing_registers_qmatmul_by_hand() {
    let files = indexed("fuel-dispatch/src", ".rs");
    assert!(files.len() > 50, "only {} source files found", files.len());

    let mut registration_file_gated = false;
    let mut loads_contract = false;
    let mut calls_registrar = false;
    let mut by_hand = Vec::new();
    for path in &files {
        let text = std::fs::read_to_string(path).expect("read source");
        if path.ends_with("baracuda_dispatch.rs") {
            registration_file_gated = text
                .lines()
                .any(|l| l.trim() == "#![cfg(feature = \"cuda\")]");
            loads_contract =
                text.contains("include_str!(\"../kernel-contracts/cuda/qmatmul.fkc.md\")");
            calls_registrar = text
                .lines()
                .any(|l| l.trim() == "register_cuda_qmatmul_from_contract(table);");
        }
        for line in cuda_qmatmul_lines(&text) {
            by_hand.push(format!("{}:{line}", path.display()));
        }
    }
    // Control: the scan reached the CUDA registration file and recognised its gate.
    assert!(
        registration_file_gated,
        "the scan did not recognise baracuda_dispatch.rs as the CUDA-gated registration file"
    );
    assert!(
        loads_contract,
        "{WHY}: baracuda_dispatch.rs no longer includes cuda/qmatmul.fkc.md"
    );
    assert!(
        calls_registrar,
        "{WHY}: register_baracuda_cuda_kernels no longer registers it"
    );
    assert!(
        by_hand.is_empty(),
        "a CUDA-gated source registers QMatMul by hand; the contract is the sole path: {by_hand:?}"
    );
}
