//! FlashAttn backward — produces dQ, dK, dV given (Q, K, V, dO, [alibi]).
//!
//! Three separate FusedOpId variants (FLASH_ATTN_BACKWARD_Q/K/V) share
//! one `FusedOpParams::FlashAttnBackward` payload. Each variant's
//! output shape matches the corresponding forward input's shape:
//!   Q-backward → Q-shape, K-backward → K-shape, V-backward → V-shape.
//!
//! v1 design: each backward variant recomputes the softmax state
//! independently. A single-launch / multi-output variant that shares
//! the recompute pass across all three gradients is a follow-up; the
//! current design wins on Op-IR-additivity (no multi-output enum
//! infrastructure) at the cost of 3× recompute on the math-definition
//! CPU reference. GPU kernels can fuse the recompute when they ship.
//!
//! Pattern recognition is `SubgraphPattern::None` — no autogenerated
//! lowering rule fires this op family from primitives; autograd emits
//! it directly when computing gradients through a FlashAttn forward.
//!
//! ## Increment C, C-T4 — Q/K recipe migration + the V bind-gap
//!
//! The Q and K gradients reference every fused-node input, so their
//! `decompose` bodies migrated from imperative `graph.push` calls onto a
//! declarative [`PatternNode`] recipe re-emitted through
//! [`decompose_via_recipe`] + `tag_to_op`/`emit` — reusing the C-T3
//! [`super::flash_attn::recompute_probs_recipe`] for the shared softmax-state
//! recompute (now returning `k_rep` + `softcap_tanh` too) and the C-T2
//! nested-fused carrier for the softmax **backward** (`Op::Fused(
//! SOFTMAX_LAST_DIM_BACKWARD)` rides as an `OpTag::Fused` node).
//!
//! The **V** gradient is `dV = Pᵀ·dO`, which does NOT depend on V — so a recipe
//! over the node's `[q, k, v, do, …]` inputs would leave bind 2 (`v`)
//! unreferenced. That is a `NonContiguousBinds` decline from the ONE shared
//! `validate_recipe` invariant (bind `i` ⇔ input `i`, contiguous `[0, n)` —
//! load-bearing for the runtime-fused ingestion identity, deliberately NOT
//! weakened for one op). So the V variant stays the always-correct **imperative
//! primitive form** (unchanged from the pre-C-T4 body): a documented
//! registry-layer expressibility gap, never a crash — the sibling of
//! `flash_attn`'s symbolic-`k_len` gap.

