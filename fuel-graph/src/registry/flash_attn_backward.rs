// --- recipe builders (Increment C, C-T4) -------------------------------------
// Tiny constructors for the portable [`PatternNode`] recipe data. Every extent
// and diagonal is a concrete integer at decompose time, so shape-changer nodes
// carry a BAKED absolute `target_shape` and scalar-param ops bake their concrete
// value (the FSCE / flash_attn posture) — the Q/K recipe mirrors the pre-C-T4
// imperative body node-for-node. Reuses the C-T2 nested-fused carrier for the
// softmax backward (mechanism 2a).

fn r_op(op: OpTag, attrs: OpAttrs, operands: Vec<PatternNode>) -> PatternNode {
    PatternNode::Op { op, attrs, operands }
}
fn r_bind(i: u8) -> PatternNode {
    PatternNode::Bind { index: i }
}
/// A baked absolute `target_shape` attr for a shape-changer (Reshape).
fn r_shape(dims: &[usize]) -> OpAttrs {
    OpAttrs { target_shape: dims.iter().map(|&d| d as i64).collect(), ..OpAttrs::default() }
}
/// A baked scalar for a scalar-param op (MulScalar/AddScalar) — NOT an open slot.
fn r_scalar(v: f64) -> OpAttrs {
    OpAttrs { scalars: vec![v], ..OpAttrs::default() }
}
/// An absolute permutation attr.
fn r_perm(p: Vec<u8>) -> OpAttrs {
    OpAttrs { perm: p, ..OpAttrs::default() }
}
/// A single-axis attr (SumDim reduces `attrs.axis`).
fn r_axis(a: i64) -> OpAttrs {
    OpAttrs { axis: Some(a), ..OpAttrs::default() }
}
/// The nested-softmax-**backward** selector attr (mechanism 2a): names the
/// `SoftmaxLastDimBackward` registry entry the C-T2 carrier reconstructs to
/// (the param-less `fid -> params` map already covers it).
fn fused_softmax_backward_attr() -> OpAttrs {
    OpAttrs { fused_op: Some("SoftmaxLastDimBackward".to_string()), ..OpAttrs::default() }
}

/// GQA fold as recipe DATA (mirrors the imperative `fold` closure — the inverse
/// of the forward's head-repeat): sum the `g` repeated heads back from `Hq` to
/// `Hkv` via `Reshape([b, hkv, g, s, d]) → SumDim(2)` (`SumDim` REMOVES the
/// reduced axis, so the result is `[b, hkv, s, d]`; no keepdim). Identity when
/// `Hq == Hkv`. `SumDim`'s output shape is derived by `primitive_shape`; only the
/// `Reshape` carries a baked target.
fn fold_recipe(x: PatternNode, b: usize, hkv: usize, hq: usize, s: usize, d: usize) -> PatternNode {
    if hq == hkv {
        return x;
    }
    let g = hq / hkv;
    let r5 = r_op(OpTag::Reshape, r_shape(&[b, hkv, g, s, d]), vec![x]);
    r_op(OpTag::SumDim, r_axis(2), vec![r5])
}

/// The Q/K backward gradient as portable [`PatternNode`] DATA (Increment C,
/// C-T4) — the structure-preserving migration of the pre-C-T4 imperative
/// `decompose` body for the Q and K variants. `variant` selects dQ vs dK via
/// ordinary Rust control flow (mechanism 1); the shared softmax-state recompute
/// rides [`super::flash_attn::recompute_probs_recipe`], and the softmax backward
/// rides an `OpTag::Fused(SOFTMAX_LAST_DIM_BACKWARD)` carrier (mechanism 2a). All
/// extents / diagonals are baked per call — ZERO open scalar slots.
///
/// Bind space (the fused node's input order): `0 = q`, `1 = k`, `2 = v`,
/// `3 = dO`, `4 = alibi_slopes` (present iff `has_alibi`). Both Q and K reference
/// every bind — Q uses `k_rep` for dQ and `v_rep` for dP; K uses `q` for dK and
/// `v_rep` for dP — so the binds are contiguous `[0, n)` (unlike V, which drops
/// `v` and therefore stays imperative).
///
/// The math (backward is always the top-left `q_pos_offset = 0` / full-K form —
/// the backward never slices K/V):
///
/// ```text
///   P      = recompute softmax( scale·QKᵀ [+softcap][+alibi][+mask] )
///   dP     = dO · V_repᵀ
///   dScaled = softmax_bwd(P, dP)   [softcap: · (1 − tanh²(s/cap))]
///   dScores = scale · dScaled
///   dQ     = dScores · K_rep                              # Q variant
///   dK     = fold( dScoresᵀ · Q )   (Hq → Hkv sum-fold)   # K variant
/// ```
#[allow(clippy::too_many_arguments)]
fn recipe_qk(
    variant: FusedOpId,
    b: usize,
    hq: usize,
    sq: usize,
    d: usize,
    hkv: usize,
    sk: usize,
    scale: f32,
    causal: bool,
    window_l: Option<usize>,
    window_r: Option<usize>,
    softcap: Option<f32>,
    has_alibi: bool,
    dtype: DType,
) -> PatternNode {
    // Shared recompute of P (softmax probs), the repeated K/V, and (softcap) the
    // saved tanh — over q=bind0, k=bind1, v=bind2, alibi=bind4. The backward
    // always attends the full K bottom-left-aligned (`q_pos_offset = 0`).
    let alibi = if has_alibi { Some(r_bind(4)) } else { None };
    let rc = super::flash_attn::recompute_probs_recipe(
        r_bind(0), r_bind(1), r_bind(2), alibi, b, hq, sq, sk, d, hkv, scale, causal, window_l,
        window_r, softcap, /* q_pos_offset */ 0, dtype,
    );

    // dP = dO · V_repᵀ ; dScaled = softmax_bwd(P, dP).
    let vt = r_op(OpTag::Permute, r_perm(vec![0, 1, 3, 2]), vec![rc.v_rep]);
    let dp = r_op(OpTag::MatMul, OpAttrs::default(), vec![r_bind(3), vt]);
    let mut dscaled = r_op(OpTag::Fused, fused_softmax_backward_attr(), vec![rc.probs, dp]);

    // softcap backprop: d/ds[cap·tanh(s/cap)] = 1 − tanh²(s/cap). The saved
    // `tanh` (`t`) is the SAME node emit derives inside `probs` (identity-share).
    if let Some(t) = rc.softcap_tanh {
        let t2 = r_op(OpTag::Mul, OpAttrs::default(), vec![t.clone(), t]);
        let neg = r_op(OpTag::MulScalar, r_scalar(-1.0), vec![t2]);
        let omt2 = r_op(OpTag::AddScalar, r_scalar(1.0), vec![neg]);
        dscaled = r_op(OpTag::Mul, OpAttrs::default(), vec![dscaled, omt2]);
    }
    let dscores = r_op(OpTag::MulScalar, r_scalar(scale as f64), vec![dscaled]);

    if variant == FusedOps::FLASH_ATTN_BACKWARD_Q {
        // dQ = dScores · K_rep  →  [b, hq, sq, d]
        return r_op(OpTag::MatMul, OpAttrs::default(), vec![dscores, rc.k_rep]);
    }
    // K variant: dK = dScoresᵀ · Q  →  [b, hq, sk, d]  →  fold → [b, hkv, sk, d]
    let dst = r_op(OpTag::Permute, r_perm(vec![0, 1, 3, 2]), vec![dscores]);
    let dk_rep = r_op(OpTag::MatMul, OpAttrs::default(), vec![dst, r_bind(0)]);
    fold_recipe(dk_rep, b, hkv, hq, sk, d)
}

/// Decompose to the standard SDPA backward. Re-materializing the `[Sq, Sk]`
/// score matrix is exactly what `decompose` is allowed to do (the cost-guided
/// optimizer keeps the fused kernel when present; this is the always-correct
/// primitive form). The single `FusedOpId` (Q/K/V) selects which gradient to
/// return; the recompute of `P` (softmax probs) reuses the forward's shared
/// recompute so it is byte-identical.
///
/// With `P` (probs), `K_rep`, `V_rep` and `dO` (input 3):
///   dV = Pᵀ·dO ; dP = dO·V_repᵀ ; dScaled = softmax_bwd(P, dP)
///   [softcap: dScaled·(1−tanh²)] ; dScores = scale·dScaled
///   dQ = dScores·K_rep ; dK = dScoresᵀ·Q
/// GQA folds dK/dV back from `Hq` to `Hkv` heads (the inverse of the forward's
/// head-repeat). Masked positions need no special-casing: there `P = 0`, so
/// `softmax_bwd` already yields 0.
///
/// Since C-T4 the **Q and K** variants re-emit the [`recipe_qk`] data through the
/// [`decompose_via_recipe`] bridge (structure-preserving: the emitted base map is
/// node-for-node identical to the pre-C-T4 imperative body — see the parity test
/// in `tests`). The **V** variant keeps the imperative form: `dV = Pᵀ·dO` does
/// not reference V, so a recipe would leave bind 2 unreferenced (a
/// `NonContiguousBinds` decline from the shared bind-contiguity invariant). Per
/// G2 `decompose` is total + never-panic: a wrong-params payload or a malformed
/// node returns `id` (the driver's fixpoint signal) before any emission.
fn decompose(graph: &mut Graph, id: NodeId, params: &FusedOpParams) -> NodeId {
    // The FusedOpId distinguishes which gradient (Q/K/V); params are shared.
    let variant = if let Op::Fused(fid, _) = &graph.node(id).op {
        *fid
    } else {
        return id;
    };
    let (scale, causal, window_l, window_r, softcap) = match params {
        FusedOpParams::FlashAttnBackward {
            softmax_scale,
            causal,
            window_size_left,
            window_size_right,
            softcap,
        } => (
            *softmax_scale,
            *causal,
            *window_size_left,
            *window_size_right,
            *softcap,
        ),
        // Wrong params for this id — can't decompose; return self.
        _ => return id,
    };

    // Shape/arity guards (never panic): a well-formed backward node has 4 (q,k,v,
    // do) or 5 (+alibi) 4-D inputs. Malformed → fixpoint self-return.
    let (q_shape, k_shape, n_inputs, dtype) = {
        let n = graph.node(id);
        if n.inputs.len() != 4 && n.inputs.len() != 5 {
            return id;
        }
        (
            graph.node(n.inputs[0]).shape.clone(),
            graph.node(n.inputs[1]).shape.clone(),
            n.inputs.len(),
            n.dtype,
        )
    };
    let q_dims = q_shape.dims();
    let k_dims = k_shape.dims();
    if q_dims.len() != 4 || k_dims.len() != 4 {
        return id;
    }
    let (b, hq, sq, d) = (q_dims[0], q_dims[1], q_dims[2], q_dims[3]);
    let (hkv, sk) = (k_dims[1], k_dims[2]);
    let has_alibi = n_inputs == 5;

    // Q/K migrate to the declarative recipe (they reference every input → binds
    // are contiguous). The nested softmax-backward rides an `OpTag::Fused`
    // carrier; shared recompute + softcap backprop + the GQA fold are all data.
    if variant == FusedOps::FLASH_ATTN_BACKWARD_Q || variant == FusedOps::FLASH_ATTN_BACKWARD_K {
        let recipe_node = recipe_qk(
            variant, b, hq, sq, d, hkv, sk, scale, causal, window_l, window_r, softcap, has_alibi,
            dtype,
        );
        // No open scalar slots (scale / softcap consts / diagonals are baked).
        return decompose_via_recipe(graph, id, &recipe_node, Some(Vec::new()));
    }
    if variant != FusedOps::FLASH_ATTN_BACKWARD_V {
        // Wrong fid for this entry family — decline (fixpoint).
        return id;
    }

    // --- V variant: imperative primitive form (documented bind-gap) -----------
    // `dV = Pᵀ·dO` does NOT reference V, so a recipe over [q,k,v,do,…] would
    // leave bind 2 (`v`) unreferenced — a `NonContiguousBinds` decline from the
    // shared `validate_recipe` invariant (load-bearing for runtime-fused
    // ingestion identity, deliberately not weakened). This is the always-correct
    // primitive form, unchanged from the pre-C-T4 body.
    let g = hq / hkv;
    let (q_id, k_id, v_id, do_id, alibi_id) = {
        let n = graph.node(id);
        let alibi = if n.inputs.len() == 5 { Some(n.inputs[4]) } else { None };
        (n.inputs[0], n.inputs[1], n.inputs[2], n.inputs[3], alibi)
    };
    let rc = super::flash_attn::recompute_probs(
        graph, q_id, k_id, v_id, alibi_id, b, hq, sq, sk, d, hkv, scale, causal, window_l,
        window_r, softcap, /* q_pos_offset */ 0, dtype,
    );

    // GQA fold: [b, hq, s, d] → [b, hkv, s, d] by summing the `g` repeated heads
    // (the inverse of `repeat_kv_heads`, hkv-major / g-minor).
    let fold = |graph: &mut Graph, x: NodeId, s: usize| -> NodeId {
        if hq == hkv {
            return x;
        }
        let r5 = graph.push(Node {
            op: Op::Reshape(Shape::from_dims(&[b, hkv, g, s, d])),
            inputs: vec![x],
            shape: Shape::from_dims(&[b, hkv, g, s, d]),
            dtype,
        });
        graph.push(Node {
            op: Op::SumDim(2),
            inputs: vec![r5],
            shape: Shape::from_dims(&[b, hkv, s, d]),
            dtype,
        })
    };

    // dV = Pᵀ · dO  →  [b, hq, sk, d]  →  fold → [b, hkv, sk, d]
    let pt = graph.push(Node {
        op: Op::Permute(vec![0, 1, 3, 2]),
        inputs: vec![rc.probs],
        shape: Shape::from_dims(&[b, hq, sk, sq]),
        dtype,
    });
    let dv_rep = graph.push(Node {
        op: Op::MatMul,
        inputs: vec![pt, do_id],
        shape: Shape::from_dims(&[b, hq, sk, d]),
        dtype,
    });
    fold(graph, dv_rep, sk)
}

