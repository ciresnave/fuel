"""Regenerate fuel-quantized/src/iq_grids.rs from llama.cpp's ggml-common.h.

Usage:
  gen_iq_grids.py write <path-to-ggml-common.h>   rewrite iq_grids.rs
  gen_iq_grids.py check <path-to-ggml-common.h>   fail if iq_grids.rs differs

The input is `ggml/src/ggml-common.h` at llama.cpp commit 9d57ce456c (the pin
recorded on `GgmlDType`). Fetch it with:
  gh api 'repos/ggml-org/llama.cpp/contents/ggml/src/ggml-common.h?ref=9d57ce456c' \
     -H 'Accept: application/vnd.github.raw' > ggml-common.h
Every table is parsed from the upstream text and its element count is checked
against the size upstream declares, so a truncated or mis-parsed table fails.
"""
import re, sys, pathlib

PIN = "9d57ce456c"
OUT = pathlib.Path(__file__).resolve().parent.parent / "fuel-quantized/src/iq_grids.rs"
# (C name, rust name, rust element type, bits)
TABLES = [
    ("ksigns_iq2xs", "KSIGNS_IQ2XS", "u8", 8),
    ("kmask_iq2xs", "KMASK_IQ2XS", "u8", 8),
    ("iq2xxs_grid", "IQ2XXS_GRID", "u64", 64),
    ("iq2xs_grid", "IQ2XS_GRID", "u64", 64),
    ("iq2s_grid", "IQ2S_GRID", "u64", 64),
    ("iq3xxs_grid", "IQ3XXS_GRID", "u32", 32),
    ("iq3s_grid", "IQ3S_GRID", "u32", 32),
    ("iq1s_grid", "IQ1S_GRID", "u64", 64),
]
HEADER = """\
// Derived in part from llama.cpp / ggml (MIT License, Copyright (c) 2023-2026 The ggml authors).
// The full licence text is in THIRD-PARTY-NOTICES.md at the repository root. No licence identifier line
// is stamped here: the file derives from somebody else's copyright.
//! Lookup tables for the grid-based IQ formats (GAP-211 B2).
//!
//! GENERATED by `scripts/gen_iq_grids.py` from `ggml/src/ggml-common.h` at
//! llama.cpp commit `{pin}`; do not edit by hand. `gen_iq_grids.py check` fails
//! if this file differs from what the script produces from that source.
//!
//! Each `u64`/`u32` grid entry holds 8/4 little-endian bytes, exactly as the C
//! `(const uint8_t *)(grid + index)` cast reads them on a little-endian host;
//! use `to_le_bytes()` to get them.

"""

def parse(src, name):
    m = re.search(r"GGML_TABLE_BEGIN\((\w+),\s*%s,\s*(\w+)\)(.*?)GGML_TABLE_END\(\)" % name, src, re.S)
    assert m, name
    size = m.group(2)
    if not size.isdigit():
        size = re.search(r"#define\s+%s\s+(\d+)" % size, src).group(1)
    vals = re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", m.group(3))
    vals = [int(v, 0) for v in vals]
    assert len(vals) == int(size), (name, len(vals), size)
    return vals

def render(src):
    out = HEADER.format(pin=PIN)
    for cname, rname, ty, bits in TABLES:
        vals = parse(src, cname)
        w = 2 if bits == 8 else bits // 4
        out += "#[rustfmt::skip]\npub const %s: [%s; %d] = [\n" % (rname, ty, len(vals))
        per = 16 if bits == 8 else (4 if bits == 64 else 8)
        for i in range(0, len(vals), per):
            row = vals[i:i + per]
            out += "    " + ", ".join("0x%0*x" % (w, v) for v in row) + ",\n"
        out += "];\n\n"
    return out.rstrip("\n") + "\n"

def main():
    mode, path = sys.argv[1], sys.argv[2]
    text = render(open(path, encoding="utf-8").read())
    if mode == "write":
        OUT.write_bytes(text.encode())
        print("wrote", OUT)
    else:
        cur = OUT.read_bytes().decode().replace("\r\n", "\n")
        if cur != text:
            sys.exit("iq_grids.rs differs from the generator output")
        print("iq_grids.rs matches the generator output")

main()
